#!/usr/bin/env node
/**
 * Turns the .ttf files in assets/fonts/ into base64 data-URI modules under
 * src/infrastructure/pdf/fonts/.
 *
 * Why base64 modules instead of reading the .ttf at runtime: next.config.js uses
 * `output: "standalone"`, and the file tracer only follows real ESM imports — a
 * runtime readFileSync(path) is invisible to it, so the font would be missing
 * from the Netlify function bundle while working fine locally.
 *
 * The fonts are shipped whole, not subset. Cormorant Garamond carries 975
 * codepoints (Latin, Latin Extended, Cyrillic); a subset would render guest
 * names with unusual accents as blanks, which is worse than ~390KB per module.
 * pdfkit still embeds only the glyphs each PDF actually uses, so the generated
 * PDFs stay small either way.
 *
 * Run with: npm run fonts:build
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "src/infrastructure/pdf/fonts");

const FONTS = [
  { ttf: "CormorantGaramond-Regular.ttf", module: "cormorant-regular.ts", constant: "CORMORANT_REGULAR_SRC" },
  { ttf: "CormorantGaramond-Light.ttf", module: "cormorant-light.ts", constant: "CORMORANT_LIGHT_SRC" },
];

mkdirSync(outDir, { recursive: true });

for (const font of FONTS) {
  const source = join(root, "assets/fonts", font.ttf);
  const base64 = readFileSync(source).toString("base64");
  const contents = `// GENERATED by scripts/generate-font-modules.mjs — do not edit.
// Source: assets/fonts/${font.ttf} (Cormorant Garamond, SIL OFL 1.1 — see assets/fonts/OFL.txt)
export const ${font.constant} = "data:font/ttf;base64,${base64}";
`;
  writeFileSync(join(outDir, font.module), contents);
  console.log(`${font.module}: ${(base64.length / 1024).toFixed(0)}KB base64`);
}
